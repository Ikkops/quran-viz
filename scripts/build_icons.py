"""Build the app icon: the mushaf's quarter mark (۞, rub el hizb), two squares
turned against each other, in lapis with a red-ink dot in its open centre,
on stone-white paper. Pure geometry, no font.

Writes the browser favicon (public/), the Android launcher icon (adaptive
vector + legacy PNGs) and the Android splash images. Colours are the DESIGN.md
tokens (--paper, --illumination, --rubric). The other marks drawn for it
(surah-length bars, open mushaf, ayah medallion) were left on the design
canvas; to use one, replace MAIN and ACCENT.

    python3 scripts/build_icons.py      # needs rsvg-convert and ImageMagick
"""

from __future__ import annotations

import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
PUBLIC = ROOT / "public"

PAPER = "#F7F8F5"
LAPIS = "#1F4FA0"
RUBRIC = "#B23A2A"

# The mark on a 100-unit square, centred on (50, 50): the eight-pointed star
# (tips 40 from the centre) with a round hole (filled even-odd), and the dot.
MAIN = (
    "M50 10L38.28 21.72L21.72 21.72L21.72 38.28L10 50L21.72 61.72L21.72 78.28"
    "L38.28 78.28L50 90L61.72 78.28L78.28 78.28L78.28 61.72L90 50L78.28 38.28"
    "L78.28 21.72L61.72 21.72Z"
    "M37 50A13 13 0 1 0 63 50A13 13 0 1 0 37 50Z"
)
ACCENT = "M44 50A6 6 0 1 0 56 50A6 6 0 1 0 44 50Z"


def mark(cx: float, cy: float, side: float) -> str:
    """The mark `side` units wide (its 100-unit square), centred on (cx, cy)."""
    k = side / 100
    return (
        f'<g transform="translate({cx - 50 * k:.2f} {cy - 50 * k:.2f}) scale({k:.5f})">'
        f'<path fill="{LAPIS}" fill-rule="evenodd" d="{MAIN}"/>'
        f'<path fill="{RUBRIC}" d="{ACCENT}"/></g>'
    )


def svg(size: int, side: float, *, radius: float = 0, circle: bool = False) -> str:
    bg = (
        f'<circle cx="{size / 2}" cy="{size / 2}" r="{size / 2}" fill="{PAPER}"/>'
        if circle
        else f'<rect width="{size}" height="{size}" rx="{radius}" fill="{PAPER}"/>'
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
        f"{bg}{mark(size / 2, size / 2, side)}</svg>\n"
    )


def vector(side_dp: float, *, mono: bool = False) -> str:
    """Android adaptive-icon layer (108dp canvas; 66dp safe circle)."""
    k = side_dp / 100
    t = 54 - 50 * k
    main, accent = ("#FF000000", "#FF000000") if mono else (LAPIS, RUBRIC)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build_icons.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="{t:.3f}" android:translateY="{t:.3f}"
        android:scaleX="{k:.6f}" android:scaleY="{k:.6f}">
        <path android:fillColor="{main}" android:fillType="evenOdd"
            android:pathData="{MAIN}"/>
        <path android:fillColor="{accent}" android:pathData="{ACCENT}"/>
    </group>
</vector>
"""


def png(svg_text: str, out: Path, w: int, h: int | None = None) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg_text)
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h or w), f.name, "-o", str(out)], check=True)
    Path(f.name).unlink()


def splash(w: int, h: int) -> str:
    """Paper with the mark centred (pre-Android-12 launch background)."""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">'
        f'<rect width="{w}" height="{h}" fill="{PAPER}"/>{mark(w / 2, h / 2, min(w, h) * 0.4)}</svg>'
    )


def main() -> None:
    # Browser tab: tight crop so the star survives 16-32px; PNG for older browsers.
    PUBLIC.mkdir(exist_ok=True)
    (PUBLIC / "favicon.svg").write_text(svg(512, 512 * 0.92, radius=96))
    png(svg(512, 512 * 0.92, radius=96), PUBLIC / "favicon-32.png", 32)
    # iOS / "add to home screen" masks the square itself.
    png(svg(512, 512 * 0.72), PUBLIC / "apple-touch-icon.png", 180)

    # Android adaptive icon (API 26+): vector foreground + monochrome (themed icons).
    # 80dp of mark: the star's tips (0.8 of it across) fill the 66dp safe circle.
    (RES / "drawable-v24/ic_launcher_foreground.xml").write_text(vector(80))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(80, mono=True))
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{PAPER}</color>\n</resources>\n'
    )
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""
    for name in ("ic_launcher", "ic_launcher_round"):
        (RES / f"mipmap-anydpi-v26/{name}.xml").write_text(adaptive)

    # Legacy launcher PNGs (API 24-25).
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        d = RES / f"mipmap-{density}"
        png(svg(512, 512 * 0.72, radius=96), d / "ic_launcher.png", px)
        png(svg(512, 512 * 0.62, circle=True), d / "ic_launcher_round.png", px)
        (d / "ic_launcher_foreground.png").unlink(missing_ok=True)

    # Launch background images, same sizes as Capacitor's defaults.
    for f in RES.glob("drawable*/splash.png"):
        out = subprocess.run(["identify", "-format", "%w %h", str(f)], capture_output=True, text=True, check=True)
        w, h = map(int, out.stdout.split())
        png(splash(w, h), f, w, h)

    print("icons written")


if __name__ == "__main__":
    main()
