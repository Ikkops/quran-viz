"""Build the app icon: اِقْرَأْ ("Read", the first revealed word) in Amiri Bold,
letters in lapis, vowel marks in the mushaf's red ink, on stone-white paper.

Writes the browser favicon (public/), the Android launcher icon (adaptive
vector + legacy PNGs) and the Android splash images. Colours are the DESIGN.md
tokens (--paper, --illumination, --rubric).

    python3 -m pip install uharfbuzz fonttools brotli   # once
    python3 scripts/build_icons.py                      # needs rsvg-convert

The font is read from node_modules (@fontsource/amiri), so run `npm install` first.
"""

from __future__ import annotations

import io
import subprocess
import tempfile
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource/amiri/files/amiri-arabic-700-normal.woff2"
RES = ROOT / "android/app/src/main/res"
PUBLIC = ROOT / "public"

TEXT = "اِقْرَأْ"
PAPER = "#F7F8F5"
LAPIS = "#1F4FA0"
RUBRIC = "#B23A2A"


def shape(text: str) -> tuple[str, str, tuple[float, float, float, float]]:
    """Letters and marks as two SVG path strings (font units, y down) + bbox."""
    tt = TTFont(FONT)
    tt.flavor = None
    raw = io.BytesIO()
    tt.save(raw)
    tt = TTFont(io.BytesIO(raw.getvalue()))
    font = hb.Font(hb.Face(hb.Blob(raw.getvalue())))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True})

    gs, order = tt.getGlyphSet(), tt.getGlyphOrder()
    classes = tt["GDEF"].table.GlyphClassDef.classDefs
    letters, marks = [], []
    box = [1e9, 1e9, -1e9, -1e9]
    x = 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        t = (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)
        sp, bp = SVGPathPen(gs), BoundsPen(gs)
        gs[name].draw(TransformPen(sp, t))
        gs[name].draw(TransformPen(bp, t))
        if bp.bounds:
            b = bp.bounds
            box = [min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3])]
            (marks if classes.get(name) == 3 else letters).append(sp.getCommands())
        x += pos.x_advance
    return " ".join(letters), " ".join(marks), tuple(box)  # type: ignore[return-value]


LETTERS, MARKS, BOX = shape(TEXT)


def placement(size: float, height: float, dx: float = 0.0, dy: float = 0.0):
    """Scale + translate so the word is `height` tall, centred in `size`."""
    x0, y0, x1, y1 = BOX
    k = height / (y1 - y0)
    tx = size / 2 - (x0 + x1) / 2 * k + dx * size
    ty = size / 2 - (y0 + y1) / 2 * k + dy * size
    return k, tx, ty


def svg(size: int, height: float, *, radius: float | None = 0, bg: str | None = PAPER,
        circle: bool = False, dy: float = 0.0) -> str:
    k, tx, ty = placement(size, height, dy=dy)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">']
    if bg and circle:
        parts.append(f'<circle cx="{size/2}" cy="{size/2}" r="{size/2}" fill="{bg}"/>')
    elif bg:
        parts.append(f'<rect width="{size}" height="{size}" rx="{radius}" fill="{bg}"/>')
    parts.append(f'<g transform="translate({tx:.2f} {ty:.2f}) scale({k:.5f})">')
    parts.append(f'<path fill="{LAPIS}" d="{LETTERS}"/>')
    parts.append(f'<path fill="{RUBRIC}" d="{MARKS}"/>')
    parts.append("</g></svg>\n")
    return "".join(parts)


def vector(height_dp: float, *, mono: bool = False) -> str:
    """Android adaptive-icon layer (108dp canvas; 66dp safe circle)."""
    k, tx, ty = placement(108, height_dp, dy=0.01)
    fill = "#FF000000" if mono else None
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build_icons.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}"
        android:scaleX="{k:.6f}" android:scaleY="{k:.6f}">
        <path android:fillColor="{fill or LAPIS}" android:pathData="{LETTERS}"/>
        <path android:fillColor="{fill or RUBRIC}" android:pathData="{MARKS}"/>
    </group>
</vector>
"""


def png(svg_text: str, out: Path, w: int, h: int | None = None) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg_text)
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h or w), f.name, "-o", str(out)], check=True)
    Path(f.name).unlink()


def splash(w: int, h: int) -> str:
    """Paper with the word centred (pre-Android-12 launch background)."""
    side = min(w, h) * 0.34
    x0, y0, x1, y1 = BOX
    k = side / (y1 - y0)
    tx = w / 2 - (x0 + x1) / 2 * k
    ty = h / 2 - (y0 + y1) / 2 * k
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">'
        f'<rect width="{w}" height="{h}" fill="{PAPER}"/>'
        f'<g transform="translate({tx:.2f} {ty:.2f}) scale({k:.5f})">'
        f'<path fill="{LAPIS}" d="{LETTERS}"/><path fill="{RUBRIC}" d="{MARKS}"/></g></svg>'
    )


def main() -> None:
    # Browser tab: tight crop so the word survives 16-32px; PNG for older browsers.
    PUBLIC.mkdir(exist_ok=True)
    (PUBLIC / "favicon.svg").write_text(svg(512, 512 * 0.80, radius=96, dy=0.005))
    png(svg(512, 512 * 0.80, radius=96, dy=0.005), PUBLIC / "favicon-32.png", 32)
    # iOS / "add to home screen" masks the square itself.
    png(svg(512, 512 * 0.66), PUBLIC / "apple-touch-icon.png", 180)

    # Android adaptive icon (API 26+): vector foreground + monochrome (themed icons).
    (RES / "drawable-v24/ic_launcher_foreground.xml").write_text(vector(50))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(50, mono=True))
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{PAPER}</color>\n</resources>\n'
    )
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""
    for name in ("ic_launcher", "ic_launcher_round"):
        (RES / f"mipmap-anydpi-v26/{name}.xml").write_text(adaptive)

    # Legacy launcher PNGs (API 24-25).
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        d = RES / f"mipmap-{density}"
        png(svg(512, 512 * 0.62, radius=96), d / "ic_launcher.png", px)
        png(svg(512, 512 * 0.56, circle=True), d / "ic_launcher_round.png", px)
        (d / "ic_launcher_foreground.png").unlink(missing_ok=True)

    # Launch background images, same sizes as Capacitor's defaults.
    for f in RES.glob("drawable*/splash.png"):
        out = subprocess.run(["identify", "-format", "%w %h", str(f)], capture_output=True, text=True, check=True)
        w, h = map(int, out.stdout.split())
        png(splash(w, h), f, w, h)

    print("icons written")


if __name__ == "__main__":
    main()
